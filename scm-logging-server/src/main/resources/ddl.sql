CREATE TABLE SCM_TRANSACTION_LOG
(
    id                     BIGINT NOT NULL GENERATED ALWAYS AS IDENTITY (START WITH 1, INCREMENT BY 1),
    CHANNEL_CODE           VARCHAR(255),
    TERMINAL_CODE          VARCHAR(255),
    CLIENT_ID              VARCHAR(255),
    CORRELATION_ID         VARCHAR(255),
    MESSAGE_ID             VARCHAR(36),
    CLIENT_CORRELATION_ID  VARCHAR(36),
    CLIENT_FLOW_ID         VARCHAR(255),
    SERVICE_CODE           VARCHAR(255),
    NICKNAME               VARCHAR(255),
    USERNAME               VARCHAR(255),
    DELEGATOR_USERNAME     VARCHAR(255),
    DELEGATOR_NICKNAME     VARCHAR(255),
    HOST_ADDRESS           VARCHAR(255),
    EVENT_TYPE             VARCHAR(255),
    MESSAGE_STATUS         VARCHAR(255),
    AMOUNT                 VARCHAR(255),
    CARD_NUMBER            VARCHAR(255),
    START_TIME             TIMESTAMP,
    END_TIME               TIMESTAMP,
    DURATION_MILLS         BIGINT,
    PROVIDER_CODE          VARCHAR(255),
    PROVIDER_RESPONSE_CODE VARCHAR(255),
    EXCEPTION_CLASS_NAME   VARCHAR(255),
    PAYLOAD                CLOB,
    PRIMARY KEY (id)
);